// AUTO-GENERATE mobile/lib/story-assets.ts with static require() maps for every story's
// bundled panel images + narration audio. Metro needs literal require() strings, so we emit
// them. Run AFTER bundling art (bundle-stories-art) and generating audio (gen-stories-audio).
// Stories with no bundled assets yet are simply skipped, so it is safe to run incrementally.
//   node scripts/gen-story-assets.mjs
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const DIR = join(HERE, '..', 'mobile', 'assets', 'stories');

// Curated display order (also the order stories appear in the library).
const ORDER = ['yusuf', 'musa', 'ibrahim', 'nuh', 'adam', 'maryam', 'yunus', 'sulayman', 'kahf', 'ayyub'];

function panelsIn(dir, ext) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => new RegExp(`^p\\d\\d\\.${ext}$`).test(f))
    .map((f) => parseInt(f.slice(1, 3), 10))
    .sort((a, b) => a - b);
}

function block(kind) {
  let out = '';
  for (const id of ORDER) {
    const ext = kind === 'img' ? 'jpg' : 'mp3';
    const dir = kind === 'img' ? join(DIR, id) : join(DIR, `${id}-audio`);
    const ns = panelsIn(dir, ext);
    if (!ns.length) continue;
    out += `  ${id}: {\n`;
    for (const n of ns) {
      const nn = String(n).padStart(2, '0');
      const path = kind === 'img' ? `../assets/stories/${id}/p${nn}.jpg` : `../assets/stories/${id}-audio/p${nn}.mp3`;
      out += `    ${n}: require('${path}'),\n`;
    }
    out += `  },\n`;
  }
  return out;
}

const ts = `// AUTO-GENERATED by scripts/gen-story-assets.mjs — do not edit by hand.
// Static require() maps so Metro bundles each story's reviewed panel art + narration audio.
/* eslint-disable */
export const STORY_IMAGES: Record<string, Record<number, number>> = {
${block('img')}};

export const STORY_AUDIO: Record<string, Record<number, number>> = {
${block('audio')}};
`;
writeFileSync(join(HERE, '..', 'mobile', 'lib', 'story-assets.ts'), ts);
console.log('wrote mobile/lib/story-assets.ts');
