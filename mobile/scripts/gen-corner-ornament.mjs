// Generate a slim, tintable TS module from the Corner Flourish SVG (Openclipart, CC0).
// Strips Inkscape/RDF metadata, drops the root width/height (so we size via props), collapses whitespace,
// and swaps the black fills to `currentColor` so the ornament can be tinted via the SvgXml `color` prop.
// Re-run: node scripts/gen-corner-ornament.mjs
import fs from 'node:fs';

let svg = fs.readFileSync('assets/splash/corner-flourish.svg', 'utf8');
svg = svg.replace(/<\?xml[\s\S]*?\?>/g, '');
svg = svg.replace(/<!--[\s\S]*?-->/g, '');
svg = svg.replace(/<metadata[\s\S]*?<\/metadata>/g, '');
svg = svg.replace(/<sodipodi:namedview[\s\S]*?(?:\/>|<\/sodipodi:namedview>)/g, '');
svg = svg.replace(/<title[\s\S]*?<\/title>/g, '');
svg = svg.replace(/<desc[\s\S]*?<\/desc>/g, '');
svg = svg.replace(/<defs[\s\S]*?<\/defs>/g, '');
svg = svg.replace(/\s+/g, ' ').trim();
svg = svg.replace(/\swidth="[^"]*"/, '');
svg = svg.replace(/\sheight="[^"]*"/, '');
svg = svg.replace(/#000000/gi, 'currentColor');

const out =
  '// Auto-generated by scripts/gen-corner-ornament.mjs from assets/splash/corner-flourish.svg\n' +
  '// Source: Openclipart "Corner flourish" (CC0 / public domain, no attribution required).\n' +
  '// Black fills were swapped to currentColor so the ornament tints via the SvgXml `color` prop.\n' +
  'export const CORNER_XML =\n  ' +
  JSON.stringify(svg) +
  ';\n';

fs.writeFileSync('components/splash/corner-ornament-data.ts', out);
console.log('wrote components/splash/corner-ornament-data.ts — CORNER_XML length', svg.length);
